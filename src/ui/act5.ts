import { mod } from '../nt/mod';
import { primeGroup, generators, isGenerator, subgroup } from '../nt/cyclic';
import { phiByFactor, divisors } from '../nt/phi';
import { orderByDivisors } from '../nt/order';
import { searchSpace, guess, toyExchange } from '../nt/toyDh';
import { diagram } from './strip';
import { table, check, verdict } from './common';
// Render primitive-root checks, cyclic subgroups and the toy DH secret search space.
export function act5([p, g, a, b]: bigint[]) {
  primeGroup(p);
  g = mod(g, p);
  if (g === 0n) throw Error('Choose a nonzero base modulo p.');
  const gens = generators(p),
    test = isGenerator(g, p),
    space = searchSpace(g, p),
    dh = toyExchange(g, p, a, b),
    guessed = guess(dh.secret, g, p),
    rows: string[][] = [];
  for (let x = 1n; x < p; x++)
    rows.push([
      String(x),
      String(orderByDivisors(x, p)),
      gens.includes(x) ? '<span data-generator="' + x + '">generator</span>' : 'proper subgroup',
    ]);
  let html = `<p>p = <span id="group-p">${p}</span>, checked prime by exact trial division. |ℤₚ*| = ${p - 1n}.</p>${diagram(p, space.members)}${table('Every element and its order', ['Element', 'Order', 'Role'], rows)}<p><span id="generator-count">${gens.length}</span> generators: ${gens.join(', ')}. φ(${p - 1n}) = ${phiByFactor(p - 1n)}.</p>${check('generator-count', BigInt(gens.length) === phiByFactor(p - 1n), 'Generator count equals φ(p−1).')}${table(
    'Generator test for the selected base',
    ['Prime q dividing p−1', 'g^((p−1)/q) mod p', 'Is it different from 1?'],
    test.checks.map((c) => [String(c.q), String(c.value), c.value !== 1n ? 'yes' : 'no']),
  )}${verdict('info', test.generator ? `${g} generates the whole group.` : `${g} is not a generator of the whole group. It generates a subgroup of order ${space.size}; this is an arithmetic fact, not a flaw.`, 'generator-verdict')}<h3>One subgroup for each divisor of p−1</h3><div id="subgroups">`;
  for (const d of divisors(p - 1n)) {
    const s = subgroup(d, p);
    html += `<p data-order="${d}" data-size="${s.members.length}">Order ${d}, generated by ${s.base}: {${s.members.join(', ')}}</p>`;
  }
  html +=
    '</div><p>At p = 23, ⟨2⟩ has prime order 11. This is the kind of base real finite-field Diffie–Hellman uses: <a href="https://www.rfc-editor.org/rfc/rfc7919.html#appendix-A.1">RFC 7919’s FFDHE groups</a> take g = 2 in a subgroup of prime order q = (p−1)/2. A proper subgroup is not inherently weak. Why the encoding matters belongs to <a href="https://systemslibrarian.github.io/crypto-lab-elgamal-plain/">ElGamal Plain</a>.</p>';
  const composite = [1n, 2n, 4n, 7n, 8n, 11n, 13n, 14n].map((x) => ({
    x,
    order: orderByDivisors(x, 15n)!,
  }));
  html += `<details><summary>Composite counterexample: ℤ₁₅*</summary><p>${composite.map((x) => `${x.x} → order ${x.order}`).join('; ')}. Largest order ${composite.reduce((v, x) => (x.order > v ? x.order : v), 0n)} &lt; φ(15) = ${phiByFactor(15n)}. No generator.</p></details><h3>Toy Diffie–Hellman</h3><p>A = ${dh.A}; B = ${dh.B}; shared secret = ${dh.secret}; agreement ${dh.agrees ? 'yes' : 'no'}.</p><p>Search space |⟨${g}⟩| = <span id="dh-space">${space.size}</span> possible secrets. Guesses used from g⁰ = <span id="dh-guesses">${guessed.guesses}</span>. These are different measurements.</p>${verdict(space.size <= 2n ? 'alarm' : 'info', space.size <= 2n ? `Base ${g} has order ${space.size} — only ${space.size} possible shared secrets.` : `Base ${g}: ${space.size} possible shared secrets in this small teaching group. Real groups use enormous prime orders.`, 'dh-verdict')}<p>Continue with <a href="https://systemslibrarian.github.io/crypto-lab-log-forge/">Log Forge’s Pohlig–Hellman attack</a>, <a href="https://systemslibrarian.github.io/crypto-lab-diffie-hellman-mitm/">DH MITM’s exchange</a>, or <a href="https://systemslibrarian.github.io/crypto-lab-twist-trap/">Twist Trap’s invalid-point attacks</a>.</p>`;
  return html;
}
